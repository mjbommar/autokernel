#!/usr/bin/env bash
#
# debug-boot.sh — arm a ONE-SHOT GRUB boot of any installed kernel with a
# crash-capture command line, for chasing hard freezes that leave no logs.
#
# grub-reboot can't add kernel params, so this writes a tiny extra menu entry
# (/etc/grub.d/42_autokernel_debug, placed AFTER 10_linux so GRUB_DEFAULT=0 is
# unchanged), regenerates grub.cfg, and grub-reboots into it. The one-shot is
# consumed by GRUB on that boot; the following boot is your normal default.
#
# Debug cmdline (appended to the current /proc/cmdline minus quiet/splash):
#   nmi_watchdog=1 hardlockup_panic=1   hard CPU lockup -> panic (needs CONFIG_HARDLOCKUP_DETECTOR)
#   softlockup_panic=1 hung_task_panic=1 panic_on_oops=1
#   crash_kexec_post_notifiers          let efi_pstore save dmesg BEFORE kdump takes over
#   sysrq_always_enabled=1              Alt+SysRq+C forces a crash dump if the box wedges
#   loglevel=7                          panic text visible on screen (photograph it)
#
# Usage:
#   sudo bash debug-boot.sh list                     # installed kernels + detector support
#   sudo bash debug-boot.sh arm <kver> [--reboot] [--extra "params"] [--dry-run]
#   sudo bash debug-boot.sh status                   # grubenv + current debug entry
#   sudo bash debug-boot.sh clean                    # remove the debug entry, clear next_entry
#
set -euo pipefail

GRUBD=/etc/grub.d/42_autokernel_debug
DEBUG_PARAMS="nmi_watchdog=1 hardlockup_panic=1 softlockup_panic=1 hung_task_panic=1 panic_on_oops=1 crash_kexec_post_notifiers sysrq_always_enabled=1 loglevel=7"

die() { echo "error: $*" >&2; exit 1; }
[ "$(id -u)" -eq 0 ] || die "run with sudo: sudo bash $0 ${*:-list}"

# grub-mkconfig_lib expects grub-mkconfig's environment and isn't set -u clean.
grub_lib() (
  set +u
  pkgdatadir=/usr/share/grub
  # shellcheck disable=SC1091
  . /usr/share/grub/grub-mkconfig_lib
  "$@"
)

has_hld() { grep -q '^CONFIG_HARDLOCKUP_DETECTOR=y' "/boot/config-$1" 2>/dev/null; }

cmd_list() {
  printf '%-58s %s\n' KERNEL HARDLOCKUP_DETECTOR
  for k in /boot/vmlinuz-*; do
    v=${k#/boot/vmlinuz-}
    [ -f "/boot/initrd.img-$v" ] || continue
    printf '%-58s %s\n' "$v" "$(has_hld "$v" && echo yes || echo 'NO (silent freeze stays silent)')"
  done
  echo; echo "running: $(uname -r)"
}

cmd_status() {
  grub-editenv list 2>/dev/null | grep -E 'next_entry|saved_entry|recordfail' || echo "(no next_entry armed)"
  if [ -f "$GRUBD" ]; then echo; echo "debug entry ($GRUBD):"; sed -n '/^menuentry/,/^}/p' "$GRUBD"; fi
  echo; echo "kexec_crash_loaded=$(cat /sys/kernel/kexec_crash_loaded)  (1 = kdump armed)"
}

cmd_clean() {
  rm -f "$GRUBD"
  grub-editenv - unset next_entry
  update-grub
  echo "debug entry removed; next boot is the normal default."
}

cmd_arm() {
  local kver="" reboot=0 dry=0 extra=""
  while [ $# -gt 0 ]; do
    case "$1" in
      --reboot) reboot=1 ;;
      --dry-run) dry=1 ;;
      --extra) extra="$2"; shift ;;
      -*) die "unknown flag $1" ;;
      *) kver="$1" ;;
    esac
    shift
  done
  [ -n "$kver" ] || die "usage: arm <kver>  (see: $0 list)"
  [ -f "/boot/vmlinuz-$kver" ] || die "missing /boot/vmlinuz-$kver"
  [ -f "/boot/initrd.img-$kver" ] || die "missing /boot/initrd.img-$kver"
  has_hld "$kver" || echo "WARNING: $kver lacks CONFIG_HARDLOCKUP_DETECTOR; a hard freeze will NOT panic/dump."

  # Base cmdline = what this boot used, minus BOOT_IMAGE and the boot-splash noise.
  local base
  base=$(tr ' ' '\n' </proc/cmdline | grep -vE '^(BOOT_IMAGE=|quiet$|splash$|loglevel=)' | grep . | tr '\n' ' ')
  local cmdline="${base}${DEBUG_PARAMS}${extra:+ $extra}"

  # Same device-access preamble 10_linux generates (separate ext4 /boot here).
  local prep krel irel
  prep=$(grub_lib prepare_grub_to_access_device "$(grub-probe --target=device /boot)" | sed 's/^/\t/')
  krel=$(grub_lib make_system_path_relative_to_its_root "/boot/vmlinuz-$kver")
  irel=$(grub_lib make_system_path_relative_to_its_root "/boot/initrd.img-$kver")

  local title="autokernel debug: $kver"
  local entry
  entry=$(cat <<EOF
menuentry '$title' --id autokernel-debug {
	recordfail
	load_video
	set gfxpayload=keep
	insmod gzio
$prep
	echo 'Loading $kver (debug cmdline) ...'
	linux $krel $cmdline
	initrd $irel
}
EOF
)
  local script
  script=$(printf '#!/bin/sh\n# Generated by autokernel debug-boot.sh on %s — remove with: sudo bash debug-boot.sh clean\nexec tail -n +4 "$0"\n%s\n' "$(date -Is)" "$entry")

  if [ "$dry" -eq 1 ]; then
    echo "--- would write $GRUBD ---"; echo "$script"; echo "--- then: update-grub && grub-reboot '$title'"
    return
  fi

  printf '%s\n' "$script" >"$GRUBD"
  chmod 755 "$GRUBD"
  update-grub
  grep -qF "menuentry '$title'" /boot/grub/grub.cfg || die "entry not found in grub.cfg after update-grub"
  grub-reboot "$title"
  echo
  echo "==> one-shot armed: $title"
  grub-editenv list | grep next_entry
  [ "$(cat /sys/kernel/kexec_crash_loaded)" = 1 ] || echo "WARNING: kdump not loaded on this boot (it reloads on the debug boot anyway)."
  if [ "$reboot" -eq 1 ]; then sync; systemctl reboot; else echo "reboot when ready: sudo reboot"; fi
}

case "${1:-list}" in
  list) cmd_list ;;
  status) cmd_status ;;
  clean) cmd_clean ;;
  arm) shift; cmd_arm "$@" ;;
  *) die "unknown command $1 (list|arm|status|clean)" ;;
esac
